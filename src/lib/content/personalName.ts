const DEFAULT_GROUP_WEIGHTS: PersonalNameGroup[] = Object.keys(PERSONAL_NAME_TABLES) as PersonalNameGroup[];

export interface GeneratePersonalNameOptions {
  group?: PersonalNameGroup;
  gender?: Gender;
  rng?: () => number;
}

function choice<T>(items: readonly T[], rng: () => number = Math.random): T {
  if (!items.length) throw new Error('Cannot choose from an empty list.');
  return items[Math.floor(rng() * items.length)]!;
}

function normalizeName(value: string): string {
  return value
    .replace(/s+/g, ' ')
    .replace(/ - /g, '-')
    .replace(/([’'])s+/g, '$1')
    .trim();
}

function tableMatchesGender(table: NameTable, gender: Gender): boolean {
  if (gender === 'any') return true;
  const t = table.title.toLowerCase();
  if (gender === 'masculine') return t.includes('masculine') || (!t.includes('feminine') && !t.includes('female'));
  return t.includes('feminine') || t.includes('female');
}

function looksLikeComponentTable(table: NameTable): boolean {
  const t = table.title.toLowerCase();
  return /start|ending|part|spellcasters|elven|dwarven|nanskrit|stygian/.test(t);
}

function randomFromSimpleTable(table: NameTable, rng: () => number): string {
  const row = choice(table.rows, rng);
  return normalizeName(choice(row, rng));
}

function randomFromComponentTable(table: NameTable, rng: () => number): string {
  const row = choice(table.rows, rng);
  // For component tables, a row usually contains alternate syllables/parts.
  // Joining 2-3 sampled components gives a pronounceable generated name while
  // still preserving the source table's phoneme flavor.
  const parts = row.length <= 2 ? row : [choice(row, rng), choice(row, rng)];
  return normalizeName(parts.join(''));
}

export function listPersonalNameGroups(): PersonalNameGroup[] {
  return [...DEFAULT_GROUP_WEIGHTS];
}

export function listTablesForGroup(group: PersonalNameGroup): NameTable[] {
  return Object.values(PERSONAL_NAME_TABLES[group]);
}

export function generatePersonalName(options: GeneratePersonalNameOptions = {}): string {
  const rng = options.rng ?? Math.random;
  const group = options.group ?? choice(DEFAULT_GROUP_WEIGHTS, rng);
  const gender = options.gender ?? 'any';
  const tables = listTablesForGroup(group).filter((table) => tableMatchesGender(table, gender));
  const fallbackTables = listTablesForGroup(group);
  const table = choice(tables.length ? tables : fallbackTables, rng);
  return looksLikeComponentTable(table)
    ? randomFromComponentTable(table, rng)
    : randomFromSimpleTable(table, rng);
}

export function generateManyPersonalNames(count: number, options: GeneratePersonalNameOptions = {}): string[] {
  return Array.from({ length: count }, () => generatePersonalName(options));
}

